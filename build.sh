#!/usr/bin/env bash
# 统一编译入口:引擎(hipcc)与 API(g++)全部输出到 build/,默认并行编译。
#
# 用法:
#   bash build.sh                 # all:引擎 + benchmark + API(服务器+CLI工具),并行
#   bash build.sh --bundle        # 同上，并打包分发所需的全部运行库
#   bash build.sh engine [名字]   # 只编引擎 → build/<名字>(默认 qwenox-engine)
#   bash build.sh bench           # 编译独立性能测试工具 → build/qwenox-bench
#   bash build.sh api             # 只编 API 服务器 + CLI 工具
#   bash build.sh settings        # 只编跨平台 TUI 设置工具 → ./qwenox-settings
#   bash build.sh test            # 编 ktest 并运行
#
# 产物:
#   build/qwenox-engine    引擎(src/gpu/qwenox.cpp)
#   build/qwenox-bench    独立性能测试工具(src/gpu/bench_main.cpp)
#   build/qwenox-api      API 服务器(src/api/*.cpp)
#   build/{tok_cli,tpl_cli,eng_cli,http_selftest,toolparse_test,vision_test,snap_cuts_test,inject_test}
#   build/ktest         引擎内核测试
#   build/lib/          --bundle 时生成的运行库与 gfx1151 kernel db
#
# NPU 卸载（XDNA2，已废弃保留）：检测到 XRT（XRT_DIR，默认 /opt/xilinx/xrt）
# 与 NPU 资产（NPUASSETS，默认 tools/npu，即 gufo 的 xclbin+insts 目录）时给
# engine/bench/test 编入 -DQWENOX_NPU=1（QWENOX_BUILD_NPU=0 强制不编入）。
# 运行时 QWENOX_NPU=1 才启用，默认关；启用还要求 amdxdna 驱动绑定（需内核开
# IOMMU）、FCLK 锁定、NPU 非 turbo。废弃原因见 src/gpu/parts/29_npu.inc 头部
# 注释与 attic/npu-offload/README.md。
set -euo pipefail
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"

usage() { sed -n '2,15p' "$0"; }
BUNDLE_RUNTIME=0
POSITIONAL=()
for arg in "$@"; do
  case "$arg" in
    --bundle) BUNDLE_RUNTIME=1 ;;
    -h|--help) usage; exit 0 ;;
    --*) echo "未知选项: $arg" >&2; usage >&2; exit 2 ;;
    *) POSITIONAL+=("$arg") ;;
  esac
done
set -- "${POSITIONAL[@]}"
[[ $# -le 2 ]] || { usage >&2; exit 2; }
TARGET="${1:-all}"
ENGINE_NAME="${2:-qwenox-engine}"
case "$TARGET" in
  all|engine|api|bench|settings|test) ;;
  *) usage >&2; exit 2 ;;
esac
command -v flock >/dev/null || { echo '缺少 flock，请安装 util-linux' >&2; exit 1; }
if processes="$(pgrep -af '(^|/)(qwenox[^/[:space:]]*|flash_serve|serve_api\.py)([[:space:]]|$)')"; then
  echo "已有引擎或 API 在运行，请先在原终端停止服务：$processes" >&2
  exit 1
fi
mkdir -p build
exec 9>build/.build.lock
flock -n 9 || { echo '本目录已有编译任务在运行' >&2; exit 1; }
exec 8>"${XDG_RUNTIME_DIR:-/run/user/$UID}/hgn-work.lock"
flock -n 8 || { echo '另一个 Qwenox 编译或启动任务正在运行' >&2; exit 1; }

GPU_ARCH="${GPU_ARCH:-gfx1151}"
if [[ "$TARGET" != api && "$TARGET" != settings ]]; then
  if [[ -z "${HIPCC:-}" ]]; then
    HIPCC="$(command -v hipcc || true)"
    HIPCC="${HIPCC:-/opt/rocm/bin/hipcc}"
  fi
  command -v "$HIPCC" >/dev/null || { echo '找不到 hipcc，请安装 ROCm 或设置 HIPCC' >&2; exit 1; }
fi
CXX="${CXX:-g++}"
# 版本号：唯一来源是根目录 VERSION（见 src/version.h），宏值不带引号由头文件字符串化
QWENOX_VER="$(tr -d ' \r\n' < VERSION 2>/dev/null || true)"
[[ "$QWENOX_VER" =~ ^[0-9A-Za-z.-]+$ ]] || { echo 'VERSION 文件缺失或格式不对（应形如 0.0.8）' >&2; exit 1; }
QWENOX_GITREV="$(git rev-parse --short=7 HEAD 2>/dev/null || echo nogit)"
VER_FLAGS=(-DQWENOX_VERSION_RAW="$QWENOX_VER" -DQWENOX_GIT_RAW="$QWENOX_GITREV")
echo "[版本] $QWENOX_VER ($QWENOX_GITREV)"
BUNDLE_RPATH=()
if (( BUNDLE_RUNTIME )); then
  # 旧式 DT_RPATH 让 $ORIGIN/lib 同时覆盖 ROCm 库的间接依赖。
  BUNDLE_RPATH=(-Wl,-rpath,'$ORIGIN/lib' -Wl,--disable-new-dtags)
fi
BUNDLE_SCAN_DIR="build/.runtime-scan.$$"
cleanup_build() { rm -rf -- "$BUNDLE_SCAN_DIR"; }
trap cleanup_build EXIT

# run <内存cap GB> <超时秒> <cmd...>:内存限额 + 超时保护下执行编译命令
run() {
  local cap="$1" secs="$2"; shift 2
  # 8>&- 9>&-: 编译子进程(含 systemd scope 包装)不得继承锁 fd,否则它们
  # 比父进程晚退出时,紧跟的下一个 build.sh 调用会误判"已有编译任务"
  bash tools/run_capped.sh "$cap" -- timeout -k 3 "$secs" "$@" 8>&- 9>&-
}
# compile <输出> <cap> <超时> <cmd...>:先编到临时文件,成功后原子替换
compile() {
  local output="$1" cap="$2" secs="$3"; shift 3
  local tmp="${output}.tmp.$$"
  echo "[编译] $output"
  if run "$cap" "$secs" "$@" -o "$tmp"; then
    mv -f -- "$tmp" "$output"
  else
    rm -f -- "$tmp"
    return 1
  fi
}

# ---- NPU 卸载（QWENOX_NPU，XDNA2，已废弃保留）--------------------------------
# 与 build_win.sh 同构：检测到 XRT 与资产就编入（xclbin+insts 内嵌进二进制，
# ~900KB 源文本，增量生成），运行时 QWENOX_NPU=1 才启用，默认关。
# 废弃原因见 src/gpu/parts/29_npu.inc 头部注释；不影响默认构建。
NPU_FLAGS=()
NPU_LINK=()
gen_npu_bins() {  # $1=资产目录（含 xclbin 与 insts）
  local XCLBIN="$1/final_4096x2560x1024_128x64x128.xclbin"
  local INSTS="$1/insts_4096x2560x1024_128x64x128.txt"
  local INC=build/npu_bins.inc
  [[ -f "$INC" && ! "$XCLBIN" -nt "$INC" && ! "$INSTS" -nt "$INC" ]] && return 0
  echo "[生成] $INC（内嵌 xclbin+insts）"
  {
    echo "// generated by build.sh -- embedded NPU device binaries"
    echo "static const unsigned char kXclbin[] = {"
    od -An -v -tx1 "$XCLBIN" | awk '{for(i=1;i<=NF;i++)printf "0x%s,",$i}'
    echo "};"
    echo "static const unsigned int kXclbinLen = sizeof kXclbin;"
    echo "static const unsigned char kInsts[] = {"
    od -An -v -tx1 "$INSTS" | awk '{for(i=1;i<=NF;i++)printf "0x%s,",$i}'
    echo "};"
    echo "static const unsigned int kInstsLen = sizeof kInsts;"
  } > "$INC"
}
if [[ "$TARGET" != api && "$TARGET" != settings && "${QWENOX_BUILD_NPU:-1}" != 0 ]]; then
  XRT_DIR="${XRT_DIR:-/opt/xilinx/xrt}"
  NA="${NPUASSETS:-$ROOT/tools/npu}"
  if [[ -f "$XRT_DIR/include/xrt/xrt_bo.h" &&
        -e "$XRT_DIR/lib/libxrt_coreutil.so.2" &&
        -f "$NA/final_4096x2560x1024_128x64x128.xclbin" &&
        -f "$NA/insts_4096x2560x1024_128x64x128.txt" ]] && gen_npu_bins "$NA"; then
    NPU_FLAGS=(-DQWENOX_NPU=1 -I"$XRT_DIR/include" -I"$ROOT/build")
    NPU_LINK=(-L"$XRT_DIR/lib" -l:libxrt_coreutil.so.2 -l:libxrt_core.so.2
              -Wl,-rpath,"$XRT_DIR/lib")
    echo "[NPU] 编进 engine/bench/test（运行时 QWENOX_NPU=1 启用；QWENOX_BUILD_NPU=0 不编入）"
  fi
fi

# glibc、libstdc++ 与编译器 ABI 仍由目标 Linux 提供；其余实际动态依赖
# （ROCm 闭包、libdrm/libelf 等依赖，以及 API 图像库闭包）复制到 build/lib。
is_base_system_lib() {
  case "$1" in
    libc.so.*|libm.so.*|libpthread.so.*|libdl.so.*|librt.so.*|\
    libresolv.so.*|libutil.so.*|libgcc_s.so.*|libstdc++.so.*) return 0 ;;
    *) return 1 ;;
  esac
}

bundle_binary_libs() {
  local binary="$1" scan ldd_output line soname arrow resolved rest tmp
  [[ -x "$binary" ]] || { echo "找不到待打包 ELF: $binary" >&2; return 1; }
  command -v ldd >/dev/null || { echo '缺少 ldd，无法收集 Linux 运行库' >&2; return 1; }
  mkdir -p build/lib "$BUNDLE_SCAN_DIR"

  # 在无 lib/ 邻居的临时目录解析，避免上次打包的 $ORIGIN/lib 干扰本次 ldd。
  scan="$BUNDLE_SCAN_DIR/$(basename "$binary")"
  cp -f -- "$binary" "$scan"
  if ! ldd_output="$(LC_ALL=C ldd "$scan")"; then
    echo "无法解析 $binary 的运行库" >&2
    return 1
  fi
  while IFS= read -r line; do
    read -r soname arrow resolved rest <<<"$line"
    [[ "$arrow" == '=>' ]] || continue
    if [[ "$resolved" == 'not' ]]; then
      echo "$binary 缺少运行库: $soname" >&2
      return 1
    fi
    [[ "$resolved" == /* ]] || continue
    is_base_system_lib "$soname" && continue
    tmp="build/lib/${soname}.tmp.$$"
    cp -Lf --preserve=mode,timestamps -- "$resolved" "$tmp"
    mv -f -- "$tmp" "build/lib/$soname"
    echo "[运行库] $soname"
  done <<<"$ldd_output"
}

resolve_rocm_root() {
  local hipcc_path candidate
  if [[ -n "${ROCM_PATH:-}" ]]; then
    readlink -f -- "$ROCM_PATH"
    return
  fi
  hipcc_path="$(readlink -f -- "$(command -v "$HIPCC")")"
  candidate="$(dirname -- "$(dirname -- "$hipcc_path")")"
  if [[ -d "$candidate/lib/rocblas/library" ||
        -d "$candidate/lib64/rocblas/library" ]]; then
    printf '%s\n' "$candidate"
    return
  fi
  [[ -d /opt/rocm ]] && { readlink -f /opt/rocm; return; }
  echo '无法从 HIPCC 推断 ROCm 根目录，请设置 ROCM_PATH' >&2
  return 1
}

find_kernel_db() {
  local rocm_root="$1" component="$2" candidate
  for candidate in \
    "$rocm_root/lib/$component/library" \
    "$rocm_root/lib64/$component/library"; do
    [[ -d "$candidate" ]] && { printf '%s\n' "$candidate"; return; }
  done
  candidate="$(find -L "$rocm_root" -maxdepth 5 -type d \
    -path "*/$component/library" -print -quit 2>/dev/null || true)"
  [[ -n "$candidate" ]] && { printf '%s\n' "$candidate"; return; }
  echo "找不到 $component kernel db（ROCm: $rocm_root）" >&2
  return 1
}

bundle_kernel_db() {
  local rocm_root="$1" component="$2" src dst stage item base copied=0
  local -a matches
  src="$(find_kernel_db "$rocm_root" "$component")" || return 1
  dst="build/lib/$component/library"
  stage="build/lib/$component/.library.tmp.$$"
  rm -rf -- "$stage"
  mkdir -p "$stage"

  # 新版 ROCm 按 gfx 架构分目录；旧版使用顶层带架构名的分片，两种都收集。
  if [[ -d "$src/$GPU_ARCH" ]]; then
    cp -aL -- "$src/$GPU_ARCH" "$stage/"
    copied=1
  fi
  matches=("$src/"*"$GPU_ARCH"*)
  for item in "${matches[@]}"; do
    [[ -e "$item" || -L "$item" ]] || continue
    base="$(basename -- "$item")"
    [[ "$base" == "$GPU_ARCH" ]] && continue
    cp -aL -- "$item" "$stage/"
    copied=1
  done
  (( copied )) || {
    rm -rf -- "$stage"
    echo "$component kernel db 中没有 $GPU_ARCH: $src" >&2
    return 1
  }
  rm -rf -- "$dst"
  mv -- "$stage" "$dst"
  echo "[kernel db] $dst"
}

bundle_gpu_runtime() {
  local binary="$1" rocm_root
  bundle_binary_libs "$binary"
  require_bundled_lib 'libamdhip64.so.*'
  require_bundled_lib 'librocblas.so.*'
  require_bundled_lib 'libhipblaslt.so.*'
  rocm_root="$(resolve_rocm_root)"
  bundle_kernel_db "$rocm_root" rocblas
  bundle_kernel_db "$rocm_root" hipblaslt
}

require_bundled_lib() {
  local pattern="$1"
  compgen -G "build/lib/$pattern" >/dev/null || {
    echo "运行库未打包: $pattern" >&2
    return 1
  }
}

bundle_api_runtime() {
  bundle_binary_libs "$1"
  require_bundled_lib 'libpng16.so.*'
  require_bundled_lib 'libjpeg.so.*'
  require_bundled_lib 'libwebp.so.*'
}

# 主机代码行号表（-g1，只作用于主机编译，GPU kernel 与代码生成不变）：崩溃报告里的
# "文件+偏移" 在打诊断包时由 addr2line 还原成函数与源码行。QWENOX_HOST_DEBUG=0 关闭。
HOST_DEBUG=()
[[ "${QWENOX_HOST_DEBUG:-1}" == 0 ]] || HOST_DEBUG=(-Xarch_host -g1)

build_engine() {
  compile "build/$ENGINE_NAME" 8 600 "$HIPCC" -O3 -Werror "${VER_FLAGS[@]}" "${HOST_DEBUG[@]}" \
    --offload-arch="$GPU_ARCH" "${NPU_FLAGS[@]}" src/gpu/qwenox.cpp -lrocblas -lhipblaslt \
    "${NPU_LINK[@]}" "${BUNDLE_RPATH[@]}"
}

build_bench() {
  compile build/qwenox-bench 8 600 "$HIPCC" -O3 -Werror -std=c++17 "${VER_FLAGS[@]}" \
    --offload-arch="$GPU_ARCH" "${NPU_FLAGS[@]}" -Ithird_party src/gpu/bench_main.cpp \
    -lrocblas -lhipblaslt "${NPU_LINK[@]}" "${BUNDLE_RPATH[@]}"
}

API_FLAGS=(-O2 -std=c++17 "${VER_FLAGS[@]}" -Isrc/api -Ithird_party -Ithird_party/miniz
           -Wall -Wextra -Wpedantic -Werror "${BUNDLE_RPATH[@]}")
# 静态页嵌入:编译生成器并重新生成 src/api/static_gen.inc。生成器输出是确定性的,
# 内容未变不会重写文件;static_gen.inc 是生成物,不入库(.gitignore),此处按需重新生成。
gen_static_inc() {
  if [ ! -x build/gen_static_inc ] || [ tools/gen_static_inc.cpp -nt build/gen_static_inc ]; then
    echo "[生成] build/gen_static_inc"
    "$CXX" -O2 -std=c++17 tools/gen_static_inc.cpp -o build/gen_static_inc || return 1
  fi
  echo "[生成] src/api/static_gen.inc"
  ./build/gen_static_inc src/api/static src/api/static_gen.inc
}
# tokenizer/chat_template 由 CLI 与服务器共用,每个目标须显式列出源文件
# (否则 main.cpp 会与 CLI 的 main 冲突)。
build_api() {
  gen_static_inc || return 1
  # miniz 是 C：单独按 C 编译，避免 g++/clang++ 按 C++ 语义处理 .c。
  local objdir=build/.api-obj
  mkdir -p "$objdir"
  local m
  for m in miniz miniz_tdef miniz_tinfl miniz_zip; do
    "$CXX" -O2 -x c -Ithird_party/miniz -c "third_party/miniz/$m.c" \
      -o "$objdir/$m.o" || return 1
  done
  compile build/qwenox-api 8 120 "$CXX" "${API_FLAGS[@]}" \
    src/api/http.cpp src/api/engine_client.cpp src/api/tokenizer.cpp \
    src/api/chat_template.cpp src/api/json_py.cpp src/api/toolparse.cpp \
    src/api/vision.cpp src/api/reqstat.cpp src/api/reqstat_read.cpp \
    src/api/power.cpp src/api/engine_sup.cpp src/api/snap_cuts.cpp \
    src/api/reqlog.cpp src/api/diagpack.cpp "$objdir"/miniz.o "$objdir"/miniz_tdef.o \
    "$objdir"/miniz_tinfl.o "$objdir"/miniz_zip.o \
    src/api/main.cpp -lpng -ljpeg -lwebp -lpthread || return 1
  compile build/tok_cli 8 120 "$CXX" "${API_FLAGS[@]}" \
    src/api/tokenizer.cpp src/api/tok_cli.cpp || return 1
  compile build/tpl_cli 8 120 "$CXX" "${API_FLAGS[@]}" \
    src/api/chat_template.cpp src/api/json_py.cpp src/api/tpl_cli.cpp || return 1
  compile build/eng_cli 8 120 "$CXX" "${API_FLAGS[@]}" \
    src/api/engine_client.cpp src/api/tokenizer.cpp src/api/eng_cli.cpp || return 1
  compile build/http_selftest 8 120 "$CXX" "${API_FLAGS[@]}" \
    src/api/http.cpp src/api/http_selftest.cpp -lpthread || return 1
  compile build/engine_host_test 8 120 "$CXX" "${API_FLAGS[@]}" \
    tools/engine_host_test.cpp || return 1
  compile build/toolparse_test 8 120 "$CXX" "${API_FLAGS[@]}" \
    src/api/toolparse.cpp src/api/json_py.cpp src/api/toolparse_test.cpp || return 1
  compile build/snap_cuts_test 8 120 "$CXX" "${API_FLAGS[@]}" \
    src/api/snap_cuts.cpp src/api/chat_template.cpp src/api/json_py.cpp \
    src/api/tokenizer.cpp src/api/vision.cpp src/api/snap_cuts_test.cpp \
    -lpng -ljpeg -lwebp -lpthread || return 1
  compile build/inject_test 8 120 "$CXX" "${API_FLAGS[@]}" \
    src/api/chat_template.cpp src/api/json_py.cpp src/api/tokenizer.cpp \
    src/api/vision.cpp src/api/inject_test.cpp -lpng -ljpeg -lwebp -lpthread || return 1
  compile build/vision_test 8 120 "$CXX" "${API_FLAGS[@]}" \
    src/api/vision.cpp src/api/tokenizer.cpp src/api/vision_test.cpp \
    -lpng -ljpeg -lwebp -lpthread || return 1
}

build_settings() {
  # 跨平台终端设置工具：只编辑 service.conf，不依赖 HIP/ROCm 或 ncurses。
  compile qwenox-settings 1 60 "$CXX" -O2 -std=c++17 \
    -Wall -Wextra -Wpedantic -Werror src/settings_tui.cpp -pthread
}

build_test() {
  run 8 180 python3 tools/kv_admission_test.py --cxx "$CXX" || return 1
  run 8 180 python3 tools/kv_page_test.py --cxx "$CXX" || return 1
  compile build/ktest 8 600 "$HIPCC" -O3 -Werror --offload-arch="$GPU_ARCH" \
    "${NPU_FLAGS[@]}" -I src/gpu tools/ktest.cu -lrocblas -lhipblaslt \
    "${NPU_LINK[@]}" "${BUNDLE_RPATH[@]}" || return 1
}

case "$TARGET" in
  engine)
    build_engine
    (( ! BUNDLE_RUNTIME )) || bundle_gpu_runtime "build/$ENGINE_NAME"
    ;;
  bench)
    build_bench
    (( ! BUNDLE_RUNTIME )) || bundle_gpu_runtime build/qwenox-bench
    ;;
  api)
    build_api
    (( ! BUNDLE_RUNTIME )) || bundle_api_runtime build/qwenox-api
    ;;
  settings)
    build_settings
    ;;
  test)
    build_test
    if (( BUNDLE_RUNTIME )); then
      bundle_gpu_runtime build/ktest
      run 8 600 env \
        "LD_LIBRARY_PATH=$ROOT/build/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}" \
        "ROCBLAS_TENSILE_LIBPATH=$ROOT/build/lib/rocblas/library" \
        "HIPBLASLT_TENSILE_LIBPATH=$ROOT/build/lib/hipblaslt/library" \
        build/ktest
    else
      run 8 600 build/ktest
    fi
    ;;
  all)
    pids=()
    build_engine & pids+=($!)
    build_bench  & pids+=($!)
    build_api    & pids+=($!)
    build_settings & pids+=($!)
    fail=0
    for p in "${pids[@]}"; do wait "$p" || fail=1; done
    [[ "$fail" == 0 ]] || { echo '[失败] 见上方编译输出' >&2; exit 1; }
    if (( BUNDLE_RUNTIME )); then
      bundle_gpu_runtime "build/$ENGINE_NAME"
      bundle_api_runtime build/qwenox-api
    fi
    ;;
esac
if (( BUNDLE_RUNTIME )); then
  printf 'GPU_ARCH=%s\n' "$GPU_ARCH" >build/bundled-runtime.conf
  echo '[完成] 分发产物与私有运行库位于 build/'
else
  # 仅在本轮编译成功后清理旧分发库，避免编译失败破坏上次可用产物。
  rm -rf -- build/lib
  rm -f -- build/bundled-runtime.conf
  echo '[完成] 编译输出位于 build/（使用系统运行库）'
fi
